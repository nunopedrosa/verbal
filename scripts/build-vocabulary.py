#!/usr/bin/env python3
"""Build bounded offline guess lists from pinned pt-PT Hunspell sources. Dev-only tools."""
from pathlib import Path
import json,re,subprocess,tempfile,unicodedata
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'vendor/dictionary'
def normalize(word):return ''.join(c for c in unicodedata.normalize('NFD',word) if not unicodedata.combining(c)).upper()
# The immutable editorial banks and legacy five-letter guesses remain accepted.
legacy=json.loads(subprocess.check_output(['node','-e',"const fs=require('fs'),vm=require('vm');const c={};vm.createContext(c);vm.runInContext(fs.readFileSync('public/words.js','utf8')+';this.banks=BANKS;this.words=WORDS',c);process.stdout.write(JSON.stringify({banks:c.banks,words:c.words}));"],cwd=ROOT,text=True))
accepted={n:set(legacy['banks'][str(n)]) for n in range(4,9)}
accepted[5].update(legacy['words'])
with tempfile.TemporaryDirectory(prefix='verbal-vocabulary-') as tmp:
 tmp=Path(tmp);entries=[]
 for line in (SOURCE/'index.dic').read_text().splitlines()[1:]:
  token=line.split()[0];word=token.split('/')[0]
  # Exclude proper nouns, abbreviations, hyphens and punctuation before expanding.
  if word==word.lower() and re.fullmatch('[a-záàâãéêíóôõúüç]+',word):entries.append(token)
 (tmp/'pt_PT.dic').write_text(str(len(entries))+'\n'+'\n'.join(entries)+'\n')
 (tmp/'pt_PT.aff').write_bytes((SOURCE/'index.aff').read_bytes())
 with (tmp/'expanded.txt').open('w') as out:
  subprocess.run(['unmunch',str(tmp/'pt_PT.dic'),str(tmp/'pt_PT.aff')],stdout=out,stderr=subprocess.DEVNULL,check=True)
 candidates=set()
 with (tmp/'expanded.txt').open() as words:
  for line in words:
   word=line.strip()
   normalized=normalize(word)
   if word==word.lower() and re.fullmatch('[A-Z]{4,8}',normalized):candidates.add(word)
 # Unmunch expands affixes; validate candidates against Hunspell itself before inclusion.
 checked=subprocess.run(['hunspell','-d',str(tmp/'pt_PT'),'-i','UTF-8','-G'],input='\n'.join(sorted(candidates))+'\n',text=True,capture_output=True,check=True)
 for word in checked.stdout.splitlines():
  normalized=normalize(word)
  if re.fullmatch('[A-Z]{4,8}',normalized):accepted[len(normalized)].add(normalized)
body='// Generated by scripts/build-vocabulary.py. Dictionary-derived data: MPL-1.1.\n// See dictionary-license.txt; editorial answer banks stay in words.js.\nconst GUESSES = {'
body+=','.join(json.dumps(str(n))+':`'+' '.join(sorted(accepted[n]))+'`.split(\' \')' for n in range(4,9))+'};\n'
assert len(body.encode())<1000000,'Keep the offline lexicon bounded'
(ROOT/'public/guesses.js').write_text(body)
print('Accepted guesses:',{n:len(words) for n,words in accepted.items()})
print('guesses.js bytes:',len(body.encode()))
