#!/usr/bin/env python3
"""Rebuild English data offline from pinned Hunspell sources (requires Hunspell and unmunch)."""
from pathlib import Path
import json,re,subprocess,tempfile
ROOT=Path(__file__).resolve().parents[1]; SOURCE=ROOT/'vendor/english'
data=json.loads((SOURCE/'editorial.json').read_text())
accepted={str(n):set() for n in range(4,9)}
for dialect in ('en_GB','en_US'):
 with tempfile.TemporaryDirectory() as tmp:
  tmp=Path(tmp);entries=[]
  for line in (SOURCE/(dialect+'.dic')).read_text().splitlines()[1:]:
   token=line.split()[0];word=token.split('/')[0]
   if re.fullmatch('[a-z]+',word):entries.append(token)
  dic=tmp/(dialect+'.dic');dic.write_text(str(len(entries))+'\n'+'\n'.join(entries)+'\n')
  aff=tmp/(dialect+'.aff');aff.write_bytes((SOURCE/(dialect+'.aff')).read_bytes())
  expanded=subprocess.check_output(['unmunch',str(dic),str(aff)],stderr=subprocess.DEVNULL,text=True)
  candidates=sorted(set(word for word in expanded.splitlines() if re.fullmatch('[a-z]{4,8}',word)))
  checked=subprocess.run(['hunspell','-d',str(tmp/dialect),'-i','UTF-8','-G'],input='\n'.join(candidates)+'\n',text=True,capture_output=True,check=True)
  for word in checked.stdout.splitlines():accepted[str(len(word))].add(word.upper())
for n,words in data['banks'].items():
 for word in words:
  assert word in accepted[n], 'Editorial answer absent from lowercase dictionary: '+word
 accepted[n].update(words)
for theme in data.get('themes',{}).values():
 for n,words in theme.items():accepted[n].update(words)
for n,routes in data.get('ladders',{}).items():
 for route in routes:accepted[n].update(route)
data['guesses']={n:sorted(words) for n,words in accepted.items()}
body='/* Generated by scripts/build-english.py; see english-license.txt. Editorial v1 is immutable. */\n(function(root){\'use strict\';var data='+json.dumps(data,separators=(',',':'))+';if(typeof module===\'object\'&&module.exports)module.exports=data;else root.VerbalEnglish=data;})(this);\n'
(ROOT/'public/english.js').write_text(body)
print('Answers:',{n:len(x) for n,x in data['banks'].items()})
print('Guesses:',{n:len(x) for n,x in data['guesses'].items()})
